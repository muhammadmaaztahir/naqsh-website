export const WHATSAPP_PHONE = "14156245109"; // Naqsh official WhatsApp number

export function createWhatsAppProductUrl(product: ShopProduct, selectedSize?: string, customNote?: string): string {
  const chosenSize = selectedSize || product.sizes[0] || "Standard";

  // Try to get public URL for image if available in browser environment
  let imageRef = "";
  if (typeof window !== "undefined") {
    imageRef = product.image.startsWith("http")
      ? product.image
      : `${window.location.origin}${product.image}`;
  }

  const messageLines = [
    `✨ *NAQSH ATELIER — ORDER & INQUIRY* ✨`,
    `━━━━━━━━━━━━━━━━━━━━━━`,
    `🛍️ *Product:* ${product.title}`,
    `🔖 *Item Code / SKU:* ${product.sku}`,
    `🏷️ *Brand:* ${product.brand}`,
    `👗 *Category:* ${product.category}`,
    `🧵 *Fabric:* ${product.fabric}`,
    `🎨 *Color:* ${product.color}`,
    `📏 *Selected Size:* ${chosenSize}`,
    `💰 *Price:* PKR ${product.price.toLocaleString()}`,
    imageRef ? `🖼️ *Image Ref:* ${imageRef}` : "",
    customNote ? `📝 *Special Request:* ${customNote}` : "",
    `━━━━━━━━━━━━━━━━━━━━━━`,
    `Assalam-o-Alaikum, I want to order this piece. Please confirm availability and delivery details.`,
  ].filter(Boolean);

  const message = messageLines.join("\n");
  return `https://wa.me/${WHATSAPP_PHONE}?text=${encodeURIComponent(message)}`;
}

